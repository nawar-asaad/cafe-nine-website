// عبارات ترحيب باللهجة البصراوية تظهر على شاشة القفل عند الاقتراب من المطعم.
// اجعلها قصيرة (أقل من 60 حرفاً تقريباً) حتى تظهر كاملة.
const GREETINGS = [
  'هلا بيك عيني! وينك ما مبيّن؟ تعال اشرب استكان چاي ويانا ☕',
  'اشتقنالك حيل… المكان ناقصه انت، فوت سلّم علينا',
  'يابه صرت يمّنا! لا تعبر وتمشي، تفضّل',
  'صار زمان ما شفناك، گلبنا يمّك… تعال نوّر',
  'ياهلا بالغالي، الچاي مخدّر وينتظرك',
  'وين هالغيبة؟ تعال خلّي نشوفك',
  'حيّاك الله، الأكل حار والگعدة تنراد',
  'مرّتك من يمّنا ما تصير بلاش، فوت ولو على الماشي',
];

// يختار عبارة مختلفة مع كل تحديث للبطاقة حتى لا يملّ الزبون من نفس العبارة
function pickGreeting(seed = Date.now()) {
  const n = Math.abs(Math.floor(seed)) % GREETINGS.length;
  return GREETINGS[n];
}

module.exports = { GREETINGS, pickGreeting };
